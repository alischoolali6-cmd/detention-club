-- ============ PLACE AN ORDER (public) ============
create or replace function place_order(
  p_name text, p_phone text, p_email text, p_address text, p_area text,
  p_zone_id int, p_notes text, p_items jsonb, p_accepted boolean
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  v_code text;
  v_order uuid;
  v_item jsonb;
  v_prod products%rowtype;
  v_qty int;
  v_instock int;
  v_pre int;
  v_subtotal int := 0;
  v_fee int := 0;
  v_has_pre boolean := false;
  v_lines int := 0;
  v_phone text := regexp_replace(coalesce(p_phone,''), '[^0-9+]', '', 'g');
begin
  if not coalesce(p_accepted, false) then raise exception 'You must accept the terms and privacy policy.'; end if;
  if length(trim(coalesce(p_name,''))) < 2 or length(p_name) > 80 then raise exception 'Please enter your full name.'; end if;
  if length(v_phone) < 8 or length(v_phone) > 16 then raise exception 'Please enter a valid phone number.'; end if;
  if coalesce(p_email,'') !~* '^[^@\s]+@[^@\s]+\.[^@\s]+$' or length(p_email) > 120 then raise exception 'Please enter a valid email address.'; end if;
  if length(trim(coalesce(p_address,''))) < 5 or length(p_address) > 300 then raise exception 'Please enter your full delivery address.'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'Your cart is empty.'; end if;
  if jsonb_array_length(p_items) > 30 then raise exception 'Too many different items in one order.'; end if;

  -- simple anti-spam: max 5 orders per phone per hour
  if (select count(*) from orders where phone = v_phone and created_at > now() - interval '1 hour') >= 5 then
    raise exception 'Too many orders from this phone number. Please try again later.';
  end if;

  if p_zone_id is not null then
    select fee_fils into v_fee from delivery_zones where id = p_zone_id and active;
    if not found then raise exception 'Please choose a valid delivery area.'; end if;
  end if;

  -- unique, hard-to-guess order code
  loop
    v_code := 'DC-' || (select string_agg(substr(alphabet, 1 + floor(random()*length(alphabet))::int, 1), '') from generate_series(1,6));
    exit when not exists (select 1 from orders where code = v_code);
  end loop;

  insert into orders (code, customer_name, phone, email, address, area, zone_id, notes,
                      subtotal_fils, delivery_fee_fils, total_fils, terms_accepted_at)
  values (v_code, trim(p_name), v_phone, lower(trim(p_email)), trim(p_address), nullif(trim(coalesce(p_area,'')),''),
          p_zone_id, nullif(trim(coalesce(p_notes,'')),''), 0, coalesce(v_fee,0), 0, now())
  returning id into v_order;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'qty')::int;
    if v_qty is null or v_qty < 1 or v_qty > 20 then raise exception 'Invalid quantity.'; end if;
    select * into v_prod from products where id = (v_item->>'product_id')::int and active for update;
    if not found then raise exception 'One of the items is no longer available.'; end if;
    v_instock := least(v_prod.stock, v_qty);
    v_pre := v_qty - v_instock;
    if v_instock > 0 then update products set stock = stock - v_instock where id = v_prod.id; end if;
    if v_pre > 0 then v_has_pre := true; end if;
    insert into order_items (order_id, product_id, name, qty, preorder_qty, unit_price_fils)
    values (v_order, v_prod.id, v_prod.name, v_qty, v_pre, v_prod.price_fils);
    v_subtotal := v_subtotal + v_prod.price_fils * v_qty;
    v_lines := v_lines + 1;
  end loop;

  update orders set subtotal_fils = v_subtotal, total_fils = v_subtotal + coalesce(v_fee,0), has_preorder = v_has_pre
  where id = v_order;
  insert into order_events (order_id, status) values (v_order, 'received');

  return jsonb_build_object('code', v_code, 'total_fils', v_subtotal + coalesce(v_fee,0), 'has_preorder', v_has_pre);
end $$;

-- ============ TRACK AN ORDER (public, needs the code) ============
create or replace function track_order(p_code text) returns jsonb
language plpgsql security definer set search_path = public stable as $$
declare o orders%rowtype; v jsonb;
begin
  select * into o from orders where code = upper(trim(coalesce(p_code,'')));
  if not found then return null; end if;
  select jsonb_build_object(
    'code', o.code, 'status', o.status, 'created_at', o.created_at, 'has_preorder', o.has_preorder,
    'first_name', split_part(o.customer_name, ' ', 1), 'area', o.area,
    'subtotal_fils', o.subtotal_fils, 'delivery_fee_fils', o.delivery_fee_fils, 'total_fils', o.total_fils,
    'reviewed', exists (select 1 from reviews r where r.order_id = o.id),
    'items', coalesce((select jsonb_agg(jsonb_build_object('name', i.name, 'qty', i.qty, 'preorder_qty', i.preorder_qty, 'unit_price_fils', i.unit_price_fils) order by i.id) from order_items i where i.order_id = o.id), '[]'::jsonb),
    'events', coalesce((select jsonb_agg(jsonb_build_object('status', e.status, 'at', e.created_at) order by e.id) from order_events e where e.order_id = o.id), '[]'::jsonb)
  ) into v;
  return v;
end $$;

-- ============ LEAVE A REVIEW (public, only for delivered orders) ============
create or replace function submit_review(p_code text, p_rating int, p_comment text) returns boolean
language plpgsql security definer set search_path = public as $$
declare o orders%rowtype;
begin
  select * into o from orders where code = upper(trim(coalesce(p_code,'')));
  if not found then raise exception 'Order code not found.'; end if;
  if o.status <> 'delivered' then raise exception 'You can review once your order has been delivered.'; end if;
  if p_rating < 1 or p_rating > 5 then raise exception 'Please choose 1 to 5 stars.'; end if;
  if length(trim(coalesce(p_comment,''))) < 3 or length(p_comment) > 600 then raise exception 'Please write a short review.'; end if;
  if exists (select 1 from reviews where order_id = o.id) then raise exception 'This order already has a review.'; end if;
  insert into reviews (order_id, first_name, rating, comment) values (o.id, split_part(o.customer_name,' ',1), p_rating, trim(p_comment));
  return true;
end $$;

-- ============ CHANGE ORDER STATUS (admin only) ============
create or replace function update_order_status(p_order uuid, p_status text) returns void
language plpgsql security definer set search_path = public as $$
declare o orders%rowtype;
begin
  if auth.uid() is null then raise exception 'Not allowed.'; end if;
  select * into o from orders where id = p_order for update;
  if not found then raise exception 'Order not found.'; end if;
  if p_status not in ('received','preparing','ready','out_for_delivery','delivered','cancelled') then raise exception 'Bad status.'; end if;
  if o.status = p_status then return; end if;
  -- cancelling puts the in-stock part of the order back on the shelf
  if p_status = 'cancelled' and o.status <> 'cancelled' then
    update products p set stock = p.stock + (i.qty - i.preorder_qty)
    from order_items i where i.order_id = o.id and i.product_id = p.id;
  end if;
  -- reopening a cancelled order takes the stock off the shelf again
  if o.status = 'cancelled' and p_status <> 'cancelled' then
    update products p set stock = greatest(0, p.stock - (i.qty - i.preorder_qty))
    from order_items i where i.order_id = o.id and i.product_id = p.id;
  end if;
  update orders set status = p_status where id = o.id;
  insert into order_events (order_id, status) values (o.id, p_status);
end $$;

