create extension if not exists pgcrypto;

-- ============ TABLES ============
create table if not exists products (
  id int generated by default as identity primary key,
  name text not null,
  category text not null,
  price_fils int not null check (price_fils >= 0),
  stock int not null default 0 check (stock >= 0),
  description text not null default '',
  image text,
  active boolean not null default true,
  sort int not null default 0
);

create table if not exists delivery_zones (
  id int generated by default as identity primary key,
  name text not null unique,
  fee_fils int not null check (fee_fils >= 0),
  active boolean not null default true
);

create table if not exists orders (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  customer_name text not null,
  phone text not null,
  email text not null,
  address text not null,
  area text,
  zone_id int references delivery_zones(id),
  notes text,
  subtotal_fils int not null,
  delivery_fee_fils int not null default 0,
  total_fils int not null,
  status text not null default 'received'
    check (status in ('received','preparing','ready','out_for_delivery','delivered','cancelled')),
  has_preorder boolean not null default false,
  terms_accepted_at timestamptz not null,
  created_at timestamptz not null default now()
);

create table if not exists order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references orders(id) on delete cascade,
  product_id int,
  name text not null,
  qty int not null check (qty > 0),
  preorder_qty int not null default 0 check (preorder_qty >= 0),
  unit_price_fils int not null
);

create table if not exists order_events (
  id bigint generated by default as identity primary key,
  order_id uuid not null references orders(id) on delete cascade,
  status text not null,
  created_at timestamptz not null default now()
);

create table if not exists reviews (
  id bigint generated by default as identity primary key,
  order_id uuid not null unique references orders(id) on delete cascade,
  first_name text not null,
  rating int not null check (rating between 1 and 5),
  comment text not null,
  approved boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists page_views (
  id bigint generated by default as identity primary key,
  visitor_id text,
  path text,
  referrer text,
  device text,
  at timestamptz not null default now()
);

alter table orders add column if not exists confirm_emailed_at timestamptz;
alter table orders add column if not exists delivery_emailed_at timestamptz;

create index if not exists orders_created_idx on orders (created_at desc);
create index if not exists orders_phone_idx on orders (phone, created_at desc);
create index if not exists order_items_order_idx on order_items (order_id);

