-- ============ NEW COLUMNS ============
alter table products add column if not exists allow_preorder boolean not null default true;
alter table orders add column if not exists promo_code text;
alter table orders add column if not exists discount_fils int not null default 0 check (discount_fils >= 0);
alter table orders add column if not exists delivery_block int;

-- ============ NEW TABLES ============
create table if not exists promo_codes (
  code text primary key check (code = upper(code) and length(code) between 3 and 30),
  kind text not null check (kind in ('percent','fixed')),
  value int not null check (value > 0),             -- percent (1-100) or fils
  min_order_fils int not null default 0,
  max_uses int,
  expires_at timestamptz,
  active boolean not null default true,
  note text,                                         -- who the code is for
  created_at timestamptz not null default now()
);

create table if not exists delivery_blocks (
  block int primary key check (block between 1 and 9999),
  fee_fils int not null check (fee_fils >= 0),
  active boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists stock_adjustments (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  product_id int,
  name text not null,
  qty int not null check (qty > 0),
  unit_cost_fils int not null default 0,
  reason text not null check (reason in ('sample','gift','damaged','other')),
  note text
);

alter table promo_codes       enable row level security;
alter table delivery_blocks   enable row level security;
alter table stock_adjustments enable row level security;
drop policy if exists "admin all promo_codes" on promo_codes;
create policy "admin all promo_codes" on promo_codes for all to authenticated using (true) with check (true);
drop policy if exists "public reads blocks" on delivery_blocks;
create policy "public reads blocks" on delivery_blocks for select to anon using (active);
drop policy if exists "admin all blocks" on delivery_blocks;
create policy "admin all blocks" on delivery_blocks for all to authenticated using (true) with check (true);
drop policy if exists "admin all stock_adjustments" on stock_adjustments;
create policy "admin all stock_adjustments" on stock_adjustments for all to authenticated using (true) with check (true);

-- ============ CHECK A PROMO CODE (public; shows the discount before ordering) ============
create or replace function check_promo(p_code text, p_subtotal int) returns jsonb
language plpgsql security definer set search_path = public stable as $$
declare c promo_codes%rowtype; d int; code_in text := upper(trim(coalesce(p_code,'')));
begin
  select * into c from promo_codes where code = code_in and active;
  if not found or (c.expires_at is not null and c.expires_at < now())
     or (c.max_uses is not null and (select count(*) from orders where promo_code = c.code and status <> 'cancelled') >= c.max_uses) then
    return jsonb_build_object('valid', false, 'message', 'This promo code is not valid.');
  end if;
  if p_subtotal < c.min_order_fils then
    return jsonb_build_object('valid', false, 'message', 'This code needs a minimum order of ' || to_char(c.min_order_fils / 1000.0, 'FM999990.000') || ' BD.');
  end if;
  d := case when c.kind = 'percent' then floor(p_subtotal * c.value / 100.0)::int else least(c.value, p_subtotal) end;
  return jsonb_build_object('valid', true, 'code', c.code, 'discount_fils', d,
    'label', case when c.kind = 'percent' then c.value || '% off' else to_char(c.value / 1000.0, 'FM999990.000') || ' BD off' end);
end $$;

-- ============ PLACE AN ORDER (block delivery fee, promo code, pre-order rules) ============
drop function if exists place_order(text,text,text,text,text,int,text,jsonb,boolean);
create or replace function place_order(
  p_name text, p_phone text, p_email text, p_address text, p_area text,
  p_block int, p_notes text, p_items jsonb, p_accepted boolean, p_promo text default null
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  v_code text;
  v_order uuid;
  v_item jsonb;
  v_prod products%rowtype;
  v_promo promo_codes%rowtype;
  v_qty int; v_instock int; v_pre int;
  v_subtotal int := 0; v_fee int := 0; v_disc int := 0;
  v_has_pre boolean := false;
  v_phone text := regexp_replace(coalesce(p_phone,''), '[^0-9+]', '', 'g');
  v_promo_in text := upper(trim(coalesce(p_promo,'')));
begin
  if not coalesce(p_accepted, false) then raise exception 'You must accept the terms and privacy policy.'; end if;
  if length(trim(coalesce(p_name,''))) < 2 or length(p_name) > 80 then raise exception 'Please enter your full name.'; end if;
  if length(v_phone) < 8 or length(v_phone) > 16 then raise exception 'Please enter a valid phone number.'; end if;
  if coalesce(p_email,'') !~* '^[^@\s]+@[^@\s]+\.[^@\s]+$' or length(p_email) > 120 then raise exception 'Please enter a valid email address.'; end if;
  if length(trim(coalesce(p_address,''))) < 5 or length(p_address) > 300 then raise exception 'Please enter your full delivery address.'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'Your cart is empty.'; end if;
  if jsonb_array_length(p_items) > 30 then raise exception 'Too many different items in one order.'; end if;

  if (select count(*) from orders where phone = v_phone and created_at > now() - interval '1 hour') >= 5 then
    raise exception 'Too many orders from this phone number. Please try again later.';
  end if;

  -- delivery fee by block number (once you have added block prices)
  if exists (select 1 from delivery_blocks where active) then
    if p_block is null then raise exception 'Please enter your block number.'; end if;
    select fee_fils into v_fee from delivery_blocks where block = p_block and active;
    if not found then raise exception 'We do not have a delivery price for block % yet. Please email detentionclub0@gmail.com.', p_block; end if;
  end if;

  loop
    v_code := 'DC-' || (select string_agg(substr(alphabet, 1 + floor(random()*length(alphabet))::int, 1), '') from generate_series(1,6));
    exit when not exists (select 1 from orders where code = v_code);
  end loop;

  insert into orders (code, customer_name, phone, email, address, area, delivery_block, notes,
                      subtotal_fils, delivery_fee_fils, total_fils, terms_accepted_at)
  values (v_code, trim(p_name), v_phone, lower(trim(p_email)), trim(p_address), nullif(trim(coalesce(p_area,'')),''),
          p_block, nullif(trim(coalesce(p_notes,'')),''), 0, coalesce(v_fee,0), 0, now())
  returning id into v_order;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'qty')::int;
    if v_qty is null or v_qty < 1 or v_qty > 20 then raise exception 'Invalid quantity.'; end if;
    select * into v_prod from products where id = (v_item->>'product_id')::int and active for update;
    if not found then raise exception 'One of the items is no longer available.'; end if;
    v_instock := least(v_prod.stock, v_qty);
    v_pre := v_qty - v_instock;
    if v_pre > 0 and not v_prod.allow_preorder then
      raise exception 'Only % of "%" are available right now.', v_instock, v_prod.name;
    end if;
    if v_instock > 0 then update products set stock = stock - v_instock where id = v_prod.id; end if;
    if v_pre > 0 then v_has_pre := true; end if;
    insert into order_items (order_id, product_id, name, qty, preorder_qty, unit_price_fils, unit_cost_fils)
    values (v_order, v_prod.id, v_prod.name, v_qty, v_pre, v_prod.price_fils, v_prod.cost_fils);
    v_subtotal := v_subtotal + v_prod.price_fils * v_qty;
  end loop;

  if v_promo_in <> '' then
    select * into v_promo from promo_codes where code = v_promo_in and active for update;
    if not found or (v_promo.expires_at is not null and v_promo.expires_at < now())
       or v_subtotal < v_promo.min_order_fils
       or (v_promo.max_uses is not null and (select count(*) from orders where promo_code = v_promo.code and status <> 'cancelled') >= v_promo.max_uses) then
      raise exception 'This promo code is not valid.';
    end if;
    v_disc := case when v_promo.kind = 'percent' then floor(v_subtotal * v_promo.value / 100.0)::int else least(v_promo.value, v_subtotal) end;
  end if;

  update orders set subtotal_fils = v_subtotal, discount_fils = v_disc,
         promo_code = nullif(v_promo_in,''), total_fils = v_subtotal - v_disc + coalesce(v_fee,0), has_preorder = v_has_pre
  where id = v_order;
  insert into order_events (order_id, status) values (v_order, 'received');

  return jsonb_build_object('code', v_code, 'total_fils', v_subtotal - v_disc + coalesce(v_fee,0), 'has_preorder', v_has_pre);
end $$;

-- ============ TRACK AN ORDER (adds discount + block) ============
create or replace function track_order(p_code text) returns jsonb
language plpgsql security definer set search_path = public stable as $$
declare o orders%rowtype; v jsonb;
begin
  select * into o from orders where code = upper(trim(coalesce(p_code,'')));
  if not found then return null; end if;
  select jsonb_build_object(
    'code', o.code, 'status', o.status, 'created_at', o.created_at, 'has_preorder', o.has_preorder,
    'first_name', split_part(o.customer_name, ' ', 1), 'area', o.area, 'delivery_block', o.delivery_block,
    'subtotal_fils', o.subtotal_fils, 'discount_fils', o.discount_fils, 'promo_code', o.promo_code,
    'delivery_fee_fils', o.delivery_fee_fils, 'total_fils', o.total_fils,
    'reviewed', exists (select 1 from reviews r where r.order_id = o.id),
    'items', coalesce((select jsonb_agg(jsonb_build_object('name', i.name, 'qty', i.qty, 'preorder_qty', i.preorder_qty, 'unit_price_fils', i.unit_price_fils) order by i.id) from order_items i where i.order_id = o.id), '[]'::jsonb),
    'events', coalesce((select jsonb_agg(jsonb_build_object('status', e.status, 'at', e.created_at) order by e.id) from order_events e where e.order_id = o.id), '[]'::jsonb)
  ) into v;
  return v;
end $$;

-- ============ GIVE AWAY / WRITE OFF STOCK (samples, gifts, damaged): records the loss at cost ============
create or replace function adjust_stock(p_product int, p_qty int, p_reason text, p_note text) returns void
language plpgsql security definer set search_path = public as $$
declare p products%rowtype;
begin
  if auth.uid() is null then raise exception 'Not allowed.'; end if;
  if p_qty is null or p_qty < 1 then raise exception 'Enter a quantity.'; end if;
  if p_reason not in ('sample','gift','damaged','other') then raise exception 'Bad reason.'; end if;
  select * into p from products where id = p_product for update;
  if not found then raise exception 'Unknown product.'; end if;
  if p.stock < p_qty then raise exception 'You only have % of this item in stock.', p.stock; end if;
  update products set stock = stock - p_qty where id = p.id;
  insert into stock_adjustments (product_id, name, qty, unit_cost_fils, reason, note)
  values (p.id, p.name, p_qty, p.cost_fils, p_reason, nullif(trim(coalesce(p_note,'')),''));
end $$;

-- ============ 3-MONTH CLEANUP (now also removes the block number) ============
create or replace function _purge_old_data(p_days int) returns jsonb
language plpgsql security definer set search_path = public as $$
declare n_orders int; n_views int;
begin
  update orders set customer_name = '(deleted)', phone = '', email = '', address = '', area = null, notes = null, delivery_block = null
  where status in ('delivered','cancelled') and created_at < now() - make_interval(days => p_days) and customer_name <> '(deleted)';
  get diagnostics n_orders = row_count;
  delete from page_views where at < now() - make_interval(days => p_days);
  get diagnostics n_views = row_count;
  return jsonb_build_object('orders_cleaned', n_orders, 'views_deleted', n_views);
end $$;

