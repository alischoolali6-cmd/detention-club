-- Detention Club store: UPGRADE 2 (money, costs, restock, 3-month cleanup).
-- Run this once in Supabase -> SQL Editor, AFTER supabase-setup.sql. Safe to run again.

-- ============ NEW COLUMNS ============
alter table orders add column if not exists confirm_emailed_at timestamptz;
alter table orders add column if not exists delivery_emailed_at timestamptz;
alter table orders add column if not exists delivery_cost_fils int check (delivery_cost_fils is null or delivery_cost_fils >= 0);
alter table products add column if not exists cost_fils int not null default 0 check (cost_fils >= 0);
alter table products add column if not exists reorder_level int not null default 5 check (reorder_level >= 0);
alter table order_items add column if not exists unit_cost_fils int not null default 0;

-- ============ NEW TABLES ============
-- Every money movement. amount_fils is signed: + money in, - money out.
create table if not exists ledger (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  category text not null check (category in ('opening','sale','delivery','restock','other_expense','other_income')),
  amount_fils int not null,
  note text,
  order_id uuid references orders(id) on delete set null,
  restock_id bigint
);
create unique index if not exists ledger_order_cat_idx on ledger (order_id, category) where category in ('sale','delivery') and order_id is not null;
create index if not exists ledger_at_idx on ledger (at desc);

create table if not exists restocks (
  id bigint generated by default as identity primary key,
  ordered_at timestamptz not null default now(),
  supplier text not null default 'Temu',
  total_fils int not null check (total_fils >= 0),
  note text,
  status text not null default 'ordered' check (status in ('ordered','arrived')),
  arrived_at timestamptz
);
create table if not exists restock_items (
  id bigint generated by default as identity primary key,
  restock_id bigint not null references restocks(id) on delete cascade,
  product_id int,
  name text not null,
  qty int not null check (qty > 0),
  unit_cost_fils int not null default 0
);

alter table ledger        enable row level security;
alter table restocks      enable row level security;
alter table restock_items enable row level security;
drop policy if exists "admin all ledger" on ledger;
create policy "admin all ledger" on ledger for all to authenticated using (true) with check (true);
drop policy if exists "admin all restocks" on restocks;
create policy "admin all restocks" on restocks for all to authenticated using (true) with check (true);
drop policy if exists "admin all restock_items" on restock_items;
create policy "admin all restock_items" on restock_items for all to authenticated using (true) with check (true);

-- ============ PLACE AN ORDER (now remembers what each item cost you) ============
create or replace function place_order(
  p_name text, p_phone text, p_email text, p_address text, p_area text,
  p_zone_id int, p_notes text, p_items jsonb, p_accepted boolean
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  v_code text;
  v_order uuid;
  v_item jsonb;
  v_prod products%rowtype;
  v_qty int;
  v_instock int;
  v_pre int;
  v_subtotal int := 0;
  v_fee int := 0;
  v_has_pre boolean := false;
  v_lines int := 0;
  v_phone text := regexp_replace(coalesce(p_phone,''), '[^0-9+]', '', 'g');
begin
  if not coalesce(p_accepted, false) then raise exception 'You must accept the terms and privacy policy.'; end if;
  if length(trim(coalesce(p_name,''))) < 2 or length(p_name) > 80 then raise exception 'Please enter your full name.'; end if;
  if length(v_phone) < 8 or length(v_phone) > 16 then raise exception 'Please enter a valid phone number.'; end if;
  if coalesce(p_email,'') !~* '^[^@\s]+@[^@\s]+\.[^@\s]+$' or length(p_email) > 120 then raise exception 'Please enter a valid email address.'; end if;
  if length(trim(coalesce(p_address,''))) < 5 or length(p_address) > 300 then raise exception 'Please enter your full delivery address.'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'Your cart is empty.'; end if;
  if jsonb_array_length(p_items) > 30 then raise exception 'Too many different items in one order.'; end if;

  -- simple anti-spam: max 5 orders per phone per hour
  if (select count(*) from orders where phone = v_phone and created_at > now() - interval '1 hour') >= 5 then
    raise exception 'Too many orders from this phone number. Please try again later.';
  end if;

  if p_zone_id is not null then
    select fee_fils into v_fee from delivery_zones where id = p_zone_id and active;
    if not found then raise exception 'Please choose a valid delivery area.'; end if;
  end if;

  -- unique, hard-to-guess order code
  loop
    v_code := 'DC-' || (select string_agg(substr(alphabet, 1 + floor(random()*length(alphabet))::int, 1), '') from generate_series(1,6));
    exit when not exists (select 1 from orders where code = v_code);
  end loop;

  insert into orders (code, customer_name, phone, email, address, area, zone_id, notes,
                      subtotal_fils, delivery_fee_fils, total_fils, terms_accepted_at)
  values (v_code, trim(p_name), v_phone, lower(trim(p_email)), trim(p_address), nullif(trim(coalesce(p_area,'')),''),
          p_zone_id, nullif(trim(coalesce(p_notes,'')),''), 0, coalesce(v_fee,0), 0, now())
  returning id into v_order;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'qty')::int;
    if v_qty is null or v_qty < 1 or v_qty > 20 then raise exception 'Invalid quantity.'; end if;
    select * into v_prod from products where id = (v_item->>'product_id')::int and active for update;
    if not found then raise exception 'One of the items is no longer available.'; end if;
    v_instock := least(v_prod.stock, v_qty);
    v_pre := v_qty - v_instock;
    if v_instock > 0 then update products set stock = stock - v_instock where id = v_prod.id; end if;
    if v_pre > 0 then v_has_pre := true; end if;
    insert into order_items (order_id, product_id, name, qty, preorder_qty, unit_price_fils, unit_cost_fils)
    values (v_order, v_prod.id, v_prod.name, v_qty, v_pre, v_prod.price_fils, v_prod.cost_fils);
    v_subtotal := v_subtotal + v_prod.price_fils * v_qty;
    v_lines := v_lines + 1;
  end loop;

  update orders set subtotal_fils = v_subtotal, total_fils = v_subtotal + coalesce(v_fee,0), has_preorder = v_has_pre
  where id = v_order;
  insert into order_events (order_id, status) values (v_order, 'received');

  return jsonb_build_object('code', v_code, 'total_fils', v_subtotal + coalesce(v_fee,0), 'has_preorder', v_has_pre);
end $$;

-- ============ CHANGE ORDER STATUS (now also records the money when delivered) ============
create or replace function update_order_status(p_order uuid, p_status text) returns void
language plpgsql security definer set search_path = public as $$
declare o orders%rowtype;
begin
  if auth.uid() is null then raise exception 'Not allowed.'; end if;
  select * into o from orders where id = p_order for update;
  if not found then raise exception 'Order not found.'; end if;
  if p_status not in ('received','preparing','ready','out_for_delivery','delivered','cancelled') then raise exception 'Bad status.'; end if;
  if o.status = p_status then return; end if;
  if p_status = 'cancelled' and o.status <> 'cancelled' then
    update products p set stock = p.stock + (i.qty - i.preorder_qty)
    from order_items i where i.order_id = o.id and i.product_id = p.id;
  end if;
  if o.status = 'cancelled' and p_status <> 'cancelled' then
    update products p set stock = greatest(0, p.stock - (i.qty - i.preorder_qty))
    from order_items i where i.order_id = o.id and i.product_id = p.id;
  end if;
  if p_status = 'delivered' then
    insert into ledger (category, amount_fils, note, order_id) values ('sale', o.total_fils, 'Order ' || o.code, o.id) on conflict do nothing;
  end if;
  if o.status = 'delivered' and p_status <> 'delivered' then
    delete from ledger where order_id = o.id and category = 'sale';
  end if;
  update orders set status = p_status where id = o.id;
  insert into order_events (order_id, status) values (o.id, p_status);
end $$;

-- ============ WHAT PARCEL CHARGED FOR AN ORDER (admin only) ============
create or replace function set_delivery_cost(p_order uuid, p_fils int) returns void
language plpgsql security definer set search_path = public as $$
declare o orders%rowtype;
begin
  if auth.uid() is null then raise exception 'Not allowed.'; end if;
  if p_fils is null or p_fils < 0 then raise exception 'Enter the delivery price.'; end if;
  select * into o from orders where id = p_order for update;
  if not found then raise exception 'Order not found.'; end if;
  update orders set delivery_cost_fils = p_fils where id = o.id;
  delete from ledger where order_id = o.id and category = 'delivery';
  if p_fils > 0 then
    insert into ledger (category, amount_fils, note, order_id) values ('delivery', -p_fils, 'Parcel delivery for ' || o.code, o.id);
  end if;
end $$;

-- ============ RECORD A TEMU (SUPPLIER) ORDER: takes the money out of the bank ============
create or replace function create_restock(p_total int, p_note text, p_items jsonb) returns bigint
language plpgsql security definer set search_path = public as $$
declare v_id bigint; v_item jsonb; v_prod products%rowtype; v_qty int;
begin
  if auth.uid() is null then raise exception 'Not allowed.'; end if;
  if p_total is null or p_total <= 0 then raise exception 'Enter how much you paid.'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'Pick at least one item.'; end if;
  insert into restocks (total_fils, note) values (p_total, nullif(trim(coalesce(p_note,'')),'')) returning id into v_id;
  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'qty')::int;
    if v_qty is null or v_qty < 1 then raise exception 'Bad quantity.'; end if;
    select * into v_prod from products where id = (v_item->>'product_id')::int;
    if not found then raise exception 'Unknown product.'; end if;
    insert into restock_items (restock_id, product_id, name, qty, unit_cost_fils)
    values (v_id, v_prod.id, v_prod.name, v_qty, greatest(0, coalesce((v_item->>'unit_cost_fils')::int, 0)));
  end loop;
  insert into ledger (category, amount_fils, note, restock_id)
  values ('restock', -p_total, 'Temu order #' || v_id || coalesce(': ' || nullif(trim(coalesce(p_note,'')),''), ''), v_id);
  return v_id;
end $$;

-- ============ THE TEMU ORDER ARRIVED: adds it to your stock and updates item costs ============
create or replace function receive_restock(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare r restocks%rowtype;
begin
  if auth.uid() is null then raise exception 'Not allowed.'; end if;
  select * into r from restocks where id = p_id for update;
  if not found then raise exception 'Restock not found.'; end if;
  if r.status <> 'ordered' then raise exception 'Already marked as arrived.'; end if;
  update products p set stock = p.stock + i.qty, cost_fils = case when i.unit_cost_fils > 0 then i.unit_cost_fils else p.cost_fils end
  from restock_items i where i.restock_id = r.id and i.product_id = p.id;
  update restocks set status = 'arrived', arrived_at = now() where id = r.id;
end $$;

-- ============ DELETE CUSTOMER DETAILS AFTER 3 MONTHS ============
-- Keeps the numbers (totals, items, money) so your profit history stays correct,
-- and wipes names, phones, emails, addresses and notes from finished orders.
create or replace function _purge_old_data(p_days int) returns jsonb
language plpgsql security definer set search_path = public as $$
declare n_orders int; n_views int;
begin
  update orders set customer_name = '(deleted)', phone = '', email = '', address = '', area = null, notes = null
  where status in ('delivered','cancelled') and created_at < now() - make_interval(days => p_days) and customer_name <> '(deleted)';
  get diagnostics n_orders = row_count;
  delete from page_views where at < now() - make_interval(days => p_days);
  get diagnostics n_views = row_count;
  return jsonb_build_object('orders_cleaned', n_orders, 'views_deleted', n_views);
end $$;

create or replace function purge_old_data(p_days int default 90) returns jsonb
language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then raise exception 'Not allowed.'; end if;
  if p_days < 30 then raise exception 'Keep at least 30 days.'; end if;
  return _purge_old_data(p_days);
end $$;

-- run the cleanup automatically every Sunday at 03:00 (only works if pg_cron is available)
do $$
begin
  create extension if not exists pg_cron;
  perform cron.schedule('dc-purge-old-data', '0 3 * * 0', 'select public._purge_old_data(90)');
exception when others then
  raise notice 'Automatic weekly cleanup was not set up (pg_cron is not enabled). You can still press the cleanup button in the admin.';
end $$;

